-- Suppression de layer_display_fields et layer_rename_fields
--
-- Ces deux tables configuraient l'affichage des propriétés GeoJSON dans le panneau
-- de détail : quels champs montrer (layer_display_fields) et sous quel libellé
-- (layer_rename_fields). Le code qui les lisait a été retiré le 11 septembre 2025
-- par le commit 16c6260 « remove unecessary filters », qui a supprimé de
-- supabaseservice.js la jointure `foreignTable: 'layer_display_fields'` et les
-- champs `displayFields` / `renameFields`.
--
-- Vérifié avant suppression : aucune référence dans le dépôt (modules/, admin/,
-- fiche/, netlify/, home-src/), aucune clé étrangère entrante ou sortante, aucune
-- vue, fonction ou trigger les mentionnant. Seules subsistaient leurs propres
-- policies de lecture publique.
--
-- Le contenu au moment de la suppression est conservé plus bas : pour restaurer,
-- rejouer les CREATE TABLE puis les INSERT commentés.

drop table if exists public.layer_display_fields;
drop table if exists public.layer_rename_fields;

